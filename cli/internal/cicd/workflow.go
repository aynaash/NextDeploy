// Package cicd renders the GitHub Actions deploy workflow. It is the single
// source of truth for both `nextdeploy generate-ci` and the scaffolder, so the
// two can never drift — previously each shipped its own file (different
// runtime, different install step, different secrets), and a user who ran both
// `init` and `generate-ci` got two workflows and two deploys per push.
package cicd

import (
	"fmt"
	"strings"
)

// WorkflowPath is where the rendered workflow is written, relative to the
// repository root. Both callers use it so a scaffolded app and `generate-ci`
// produce exactly one file.
const WorkflowPath = ".github/workflows/nextdeploy.yml"

// CLIVersion pins the nextdeploy CLI installed in CI. Bump on release; keep in
// sync with .release-please-manifest.json.
//
// The generated workflows download this release's prebuilt binary and verify
// its checksum. release-please updates this pin from the package manifest.
const CLIVersion = "v1.1.0" // {x-release-please-version}

// RenderDeployWorkflow returns the YAML for WorkflowPath.
//
// The workflow knows the deployment type from nextdeploy CLI and nextdeploy.yml
// at runtime, while also supporting an explicit target type passed at generation time.
//
// Note: Application secrets (including Hyperdrive origin_env URLs) are intentionally
// not wired here — `nextdeploy apply` resolves origin_env from the shell env or
// NextDeploy's configured secret store.
func RenderDeployWorkflow(knownTarget ...string) string {
	targetType := ""
	if len(knownTarget) > 0 {
		targetType = strings.TrimSpace(knownTarget[0])
	}
	return fmt.Sprintf(`# Generated by `+"`nextdeploy generate-ci`"+` — re-run to regenerate.
#
# Target-aware: push to main and the deployment matching nextdeploy.yml runs
# from the CI runner (cloudflare | aws | vps). Retargeting the app does not
# require regenerating this file.
#
# Application secrets do NOT belong here — declare them in nextdeploy.yml so
# `+"`secenv`"+` folds them into every deploy, not just CI ones. Only per-target
# DEPLOY credentials are wired below.
name: deploy

on:
  push:
    branches: [main]
  workflow_dispatch:

# Serialize deploys per branch. Never cancel in-flight: a half-applied deploy
# is worse than a superseded one.
concurrency:
  group: nextdeploy-${{ github.ref }}
  cancel-in-progress: false

permissions:
  contents: read

jobs:
  deploy:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v4

      - uses: actions/setup-node@v4
        with:
          node-version: 22

      # Respect whichever package manager the repo actually uses.
      - name: Install app dependencies
        run: |
          if [ -f bun.lockb ] || [ -f bun.lock ]; then
            curl -fsSL https://bun.sh/install | bash
            echo "$HOME/.bun/bin" >> "$GITHUB_PATH"
            "$HOME/.bun/bin/bun" install --frozen-lockfile
          elif [ -f pnpm-lock.yaml ]; then
            corepack enable
            pnpm install --frozen-lockfile
          else
            npm ci
          fi

`+renderCLIInstallStep()+`

      # Decide the deployment type from nextdeploy CLI and nextdeploy.yml
      - name: Detect deployment type
        id: detect
        env:
          NEXTDEPLOY_TARGET_TYPE: %q
        run: |
          type="${NEXTDEPLOY_TARGET_TYPE:-}"
          if [ -z "$type" ] || [ "$type" = "auto" ]; then
            if command -v nextdeploy >/dev/null 2>&1; then
              type=$(nextdeploy target 2>/dev/null || true)
            fi
          fi
          if [ -z "$type" ] || [ "$type" = "auto" ]; then
            if grep -qE '^[[:space:]]*provider:[[:space:]]*["'\'']?cloudflare["'\'']?' nextdeploy.yml; then
              type=cloudflare
            elif grep -qE '^[[:space:]]*provider:[[:space:]]*["'\'']?aws["'\'']?' nextdeploy.yml; then
              type=aws
            elif grep -qE '^[[:space:]]*(target_type|target):[[:space:]]*["'\'']?vps["'\'']?' nextdeploy.yml || grep -qE '^[[:space:]]*(deployment|server|servers):' nextdeploy.yml || ! grep -qE '^[[:space:]]*provider:' nextdeploy.yml; then
              type=vps
            else
              echo "::error::Could not determine deployment type from nextdeploy.yml"; exit 1
            fi
          fi
          echo "type=$type" >> "$GITHUB_OUTPUT"
          echo "NEXTDEPLOY_DEPLOYMENT_TYPE=$type" >> "$GITHUB_ENV"
          echo "Deploying via: $type"

      # Only Cloudflare runs a separate `+"`apply`"+`: it reconciles D1/KV/R2/
      # Vectorize before the Worker ships. AWS provisions inside `+"`ship`"+`, and
      # VPS ships a release over SSH.
      - name: Deploy to Cloudflare
        if: steps.detect.outputs.type == 'cloudflare'
        env:
          DOPPLER_TOKEN: ${{ secrets.DOPPLER_TOKEN }}
          CLOUDFLARE_API_TOKEN: ${{ secrets.CLOUDFLARE_API_TOKEN }}
          CLOUDFLARE_ACCOUNT_ID: ${{ secrets.CLOUDFLARE_ACCOUNT_ID }}
          R2_ACCESS_KEY_ID: ${{ secrets.R2_ACCESS_KEY_ID }}
          R2_SECRET_ACCESS_KEY: ${{ secrets.R2_SECRET_ACCESS_KEY }}
          NEXTDEPLOY_CF_STATE_KEY: ${{ secrets.NEXTDEPLOY_CF_STATE_KEY }}
        run: |
          RUN_PREFIX=""
          if [ -n "${DOPPLER_TOKEN:-}" ]; then
            if ! command -v doppler >/dev/null 2>&1; then
              (curl -Ls --tlsv1.2 --proto "=https" --retry 3 https://cli.doppler.com/install.sh || wget -t 3 -qO- https://cli.doppler.com/install.sh) | sudo sh
            fi
            RUN_PREFIX="doppler run --"
          fi
          $RUN_PREFIX nextdeploy apply --yes
          $RUN_PREFIX nextdeploy ship --no-provision --verify

      - name: Deploy to AWS
        if: steps.detect.outputs.type == 'aws'
        env:
          DOPPLER_TOKEN: ${{ secrets.DOPPLER_TOKEN }}
          AWS_ACCESS_KEY_ID: ${{ secrets.AWS_ACCESS_KEY_ID }}
          AWS_SECRET_ACCESS_KEY: ${{ secrets.AWS_SECRET_ACCESS_KEY }}
          AWS_REGION: ${{ secrets.AWS_REGION }}
        run: |
          RUN_PREFIX=""
          if [ -n "${DOPPLER_TOKEN:-}" ]; then
            if ! command -v doppler >/dev/null 2>&1; then
              (curl -Ls --tlsv1.2 --proto "=https" --retry 3 https://cli.doppler.com/install.sh || wget -t 3 -qO- https://cli.doppler.com/install.sh) | sudo sh
            fi
            RUN_PREFIX="doppler run --"
          fi
          $RUN_PREFIX nextdeploy ship --verify

      - name: Deploy to VPS
        if: steps.detect.outputs.type == 'vps'
        env:
          DOPPLER_TOKEN: ${{ secrets.DOPPLER_TOKEN }}
          VPS_HOST: ${{ secrets.VPS_HOST }}
          SSH_PRIVATE_KEY: ${{ secrets.SSH_PRIVATE_KEY }}
          SSH_KNOWN_HOSTS: ${{ secrets.SSH_KNOWN_HOSTS }}
          SSH_KEY_PASSPHRASE: ${{ secrets.SSH_KEY_PASSPHRASE }}
          NEXTDEPLOY_STRICT_HOST_KEY: ${{ secrets.NEXTDEPLOY_STRICT_HOST_KEY }}
        run: |
          mkdir -p ~/.ssh
          chmod 700 ~/.ssh
          RUN_PREFIX=""
          if [ -n "${DOPPLER_TOKEN:-}" ]; then
            if ! command -v doppler >/dev/null 2>&1; then
              (curl -Ls --tlsv1.2 --proto "=https" --retry 3 https://cli.doppler.com/install.sh || wget -t 3 -qO- https://cli.doppler.com/install.sh) | sudo sh
            fi
            RUN_PREFIX="doppler run --"
            VPS_HOST=$(doppler secrets get VPS_HOST --plain 2>/dev/null || echo "$VPS_HOST")
            export VPS_HOST
            KEY=$(doppler secrets get SSH_PRIVATE_KEY --plain 2>/dev/null || echo "$SSH_PRIVATE_KEY")
            HOSTS=$(doppler secrets get SSH_KNOWN_HOSTS --plain 2>/dev/null || echo "$SSH_KNOWN_HOSTS")
            SSH_KEY_PASSPHRASE=$(doppler secrets get SSH_KEY_PASSPHRASE --plain 2>/dev/null || echo "$SSH_KEY_PASSPHRASE")
            export SSH_KEY_PASSPHRASE
          else
            KEY="$SSH_PRIVATE_KEY"
            HOSTS="$SSH_KNOWN_HOSTS"
          fi
          if [ -n "$KEY" ]; then
            echo "$KEY" > ~/.ssh/id_ed25519
            chmod 600 ~/.ssh/id_ed25519
            cp ~/.ssh/id_ed25519 ~/.ssh/id_rsa
            chmod 600 ~/.ssh/id_rsa
          fi
          if [ -n "$HOSTS" ]; then
            echo "$HOSTS" >> ~/.ssh/known_hosts
            chmod 600 ~/.ssh/known_hosts
          fi
          $RUN_PREFIX nextdeploy ship --verify
`, targetType)
}
