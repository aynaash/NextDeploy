package cicd

import (
	"fmt"
	"strings"
)

// GitLabWorkflowPath is the default location for GitLab CI/CD configuration.
const GitLabWorkflowPath = ".gitlab-ci.yml"

// RenderGitLabCIWorkflow returns the YAML for GitLabWorkflowPath.
//
// The workflow knows the deployment type from nextdeploy CLI and nextdeploy.yml
// at runtime, while also supporting an explicit target type passed at generation time.
//
// Secret Handling (Doppler-first):
//   - If DOPPLER_TOKEN is configured in GitLab CI/CD Variables, NextDeploy will
//     automatically install the Doppler CLI and run with `doppler run --`, streaming
//     secrets directly in memory.
//   - If DOPPLER_TOKEN is not provided, NextDeploy falls back to standard GitLab CI/CD
//     variables (e.g. CLOUDFLARE_API_TOKEN, AWS_ACCESS_KEY_ID, SSH_PRIVATE_KEY).
func RenderGitLabCIWorkflow(knownTarget ...string) string {
	targetType := ""
	if len(knownTarget) > 0 {
		targetType = strings.TrimSpace(knownTarget[0])
	}
	return fmt.Sprintf(`# Generated by `+"`nextdeploy generate-ci --provider=gitlab`"+` — re-run to regenerate.
#
# Target-aware: push to default branch (main/master) runs deployment matching nextdeploy.yml.
# Retargeting the app does not require regenerating this file.
#
# Secret Hardening:
# - Doppler-first: When DOPPLER_TOKEN is configured in GitLab CI/CD Variables,
#   NextDeploy automatically installs Doppler CLI and wraps execution with
#   `+"`doppler run --`"+`, streaming secrets directly in memory without disk exposure.
# - Normal way: Traditional GitLab CI/CD masked/protected variables (CLOUDFLARE_API_TOKEN,
#   AWS_ACCESS_KEY_ID, SSH_PRIVATE_KEY, etc.) are seamlessly used as fallback.

stages:
  - deploy

default:
  image: node:22-bookworm
  cache:
    key:
      files:
        - package-lock.json
        - bun.lock
        - bun.lockb
        - pnpm-lock.yaml
    paths:
      - .npm/
      - node_modules/

variables:
  CLI_VERSION: %q
  NEXTDEPLOY_TARGET_TYPE: %q

deploy:
  stage: deploy
  rules:
    - if: '$CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH'
    - if: '$CI_PIPELINE_SOURCE == "web"'
  timeout: 30 minutes
  before_script:
    - apt-get update -qq && apt-get install -y -qq curl wget sudo tar gzip openssh-client
    # Respect whichever package manager the repo actually uses
    - |
      if [ -f bun.lockb ] || [ -f bun.lock ]; then
        curl -fsSL https://bun.sh/install | bash
        export PATH="$HOME/.bun/bin:$PATH"
        bun install --frozen-lockfile
      elif [ -f pnpm-lock.yaml ]; then
        corepack enable
        pnpm install --frozen-lockfile
      else
        npm ci --cache .npm --prefer-offline
      fi
    # Install nextdeploy CLI with pinned checksum verification
    - |
      set -eu
      VERSION="${CLI_VERSION#v}"
      ARCHIVE="nextdeploy_${VERSION}_linux_amd64.tar.gz"
      RELEASE_URL="https://github.com/aynaash/NextDeploy/releases/download/${CLI_VERSION}"
      TMP_DIR="$(mktemp -d)"
      mkdir -p "$HOME/.local/bin"
      curl --fail --location --silent --show-error "$RELEASE_URL/$ARCHIVE" --output "$TMP_DIR/$ARCHIVE"
      curl --fail --location --silent --show-error "$RELEASE_URL/checksums.txt" --output "$TMP_DIR/checksums.txt"
      (cd "$TMP_DIR" && awk -v archive="$ARCHIVE" '$2 == archive { print; found=1 } END { if (!found) exit 1 }' checksums.txt | sha256sum --check --status)
      tar -xzf "$TMP_DIR/$ARCHIVE" -C "$TMP_DIR" nextdeploy
      install -m 0755 "$TMP_DIR/nextdeploy" "$HOME/.local/bin/nextdeploy"
      export PATH="$HOME/.local/bin:$PATH"
  script:
    - |
      # Resolve deployment type from nextdeploy CLI, embedded target, or nextdeploy.yml
      TYPE="${NEXTDEPLOY_TARGET_TYPE:-}"
      if [ -z "$TYPE" ] || [ "$TYPE" = "auto" ]; then
        if command -v nextdeploy >/dev/null 2>&1; then
          TYPE=$(nextdeploy target 2>/dev/null || true)
        fi
      fi
      if [ -z "$TYPE" ] || [ "$TYPE" = "auto" ]; then
        if grep -qE '^[[:space:]]*provider:[[:space:]]*["'\'']?cloudflare["'\'']?' nextdeploy.yml; then
          TYPE=cloudflare
        elif grep -qE '^[[:space:]]*provider:[[:space:]]*["'\'']?aws["'\'']?' nextdeploy.yml; then
          TYPE=aws
        elif grep -qE '^[[:space:]]*(target_type|target):[[:space:]]*["'\'']?vps["'\'']?' nextdeploy.yml || grep -qE '^[[:space:]]*(deployment|server|servers):' nextdeploy.yml || ! grep -qE '^[[:space:]]*provider:' nextdeploy.yml; then
          TYPE=vps
        else
          echo "Could not determine deployment type from nextdeploy.yml"; exit 1
        fi
      fi
      export NEXTDEPLOY_DEPLOYMENT_TYPE="$TYPE"
      echo "Deploying target type: $TYPE"

      # Install Doppler CLI if DOPPLER_TOKEN is configured
      if [ -n "${DOPPLER_TOKEN:-}" ]; then
        if ! command -v doppler >/dev/null 2>&1; then
          (curl -Ls --tlsv1.2 --proto "=https" --retry 3 https://cli.doppler.com/install.sh || wget -t 3 -qO- https://cli.doppler.com/install.sh) | sh
        fi
        RUN_PREFIX="doppler run --"
      else
        RUN_PREFIX=""
      fi

      case "$TYPE" in
        cloudflare)
          $RUN_PREFIX nextdeploy apply --yes
          $RUN_PREFIX nextdeploy ship --no-provision --verify
          ;;
        aws)
          $RUN_PREFIX nextdeploy ship --verify
          ;;
        vps)
          mkdir -p ~/.ssh
          chmod 700 ~/.ssh
          if [ -n "${DOPPLER_TOKEN:-}" ]; then
            KEY=$(doppler secrets get SSH_PRIVATE_KEY --plain 2>/dev/null || echo "${SSH_PRIVATE_KEY:-}")
            HOSTS=$(doppler secrets get SSH_KNOWN_HOSTS --plain 2>/dev/null || echo "${SSH_KNOWN_HOSTS:-}")
            SSH_KEY_PASSPHRASE=$(doppler secrets get SSH_KEY_PASSPHRASE --plain 2>/dev/null || echo "${SSH_KEY_PASSPHRASE:-}")
            export SSH_KEY_PASSPHRASE
          else
            KEY="${SSH_PRIVATE_KEY:-}"
            HOSTS="${SSH_KNOWN_HOSTS:-}"
          fi
          if [ -n "$KEY" ]; then
            echo "$KEY" > ~/.ssh/id_ed25519
            chmod 600 ~/.ssh/id_ed25519
            cp ~/.ssh/id_ed25519 ~/.ssh/id_rsa
            chmod 600 ~/.ssh/id_rsa
          fi
          if [ -n "$HOSTS" ]; then
            echo "$HOSTS" >> ~/.ssh/known_hosts
            chmod 600 ~/.ssh/known_hosts
          fi
          $RUN_PREFIX nextdeploy ship --verify
          ;;
      esac
`, CLIVersion, targetType)
}
