// maxVFSFileBytes skips oversized trace/debug artifacts while keeping every
// Next.js manifest (routes, prerender, build, client-reference, server-reference)
// safely in memory.
const maxVFSFileBytes = 2 * 1024 * 1024

// IsTurbopackTree reports whether standaloneDir/<distDir>/server/chunks
// contains Turbopack runtime/chunk markers (`[turbopack]*` or `[root-of-the-server]*`).
func IsTurbopackTree(standaloneDir, distDir string) bool {
	if distDir == "" {
		distDir = ".next"
	}
	candidates := []string{
		filepath.Join(standaloneDir, distDir, "server", "chunks"),
		filepath.Join(standaloneDir, distDir, "server", "chunks", "ssr"),
	}
	return slices.ContainsFunc(candidates, dirHasTurbopackChunk)
}

func dirHasTurbopackChunk(dir string) bool {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		name := e.Name()
		if strings.HasPrefix(name, "[turbopack]") || strings.HasPrefix(name, "[root-of-the-server]") {
			return true
		}
	}
	return false
}

// ResolveEngine selects the effective compilation engine for a standalone tree.
func ResolveEngine(requested Engine, standaloneDir, distDir string) Engine {
	switch requested {
	case EngineNextServer:
		return EngineNextServer
	case EngineLegacy:
		return EngineLegacy
	case EngineAuto:
		if IsTurbopackTree(standaloneDir, distDir) {
			return EngineNextServer
		}
		return EngineLegacy
	default:
		if IsTurbopackTree(standaloneDir, distDir) {
			return EngineNextServer
		}
		return EngineLegacy
	}
}

// EmitVirtualFS packs all Next.js manifests and metadata files from
// standaloneDir into <outDir>/_nextdeploy/vfs.mjs so NextNodeServer's
// synchronous fs.readFileSync / existsSync / readdirSync calls succeed inside
// Cloudflare Workers without a real filesystem.
func EmitVirtualFS(standaloneDir, distDir, outDir string) (string, error) {
	if distDir == "" {
		distDir = ".next"
	}
	dir := filepath.Join(outDir, "_nextdeploy")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return "", fmt.Errorf("mkdir _nextdeploy: %w", err)
	}

	files := collectVFSFiles(standaloneDir, distDir)
	dirs := buildVFSDirectoryIndex(files)
	nextCfg := extractNextConfigFromVFS(files, distDir)

	vfsPayload := struct {
		Files map[string]string   `json:"files"`
		Dirs  map[string][]string `json:"dirs"`
	}{
		Files: files,
		Dirs:  dirs,
	}
	vfsJSON, err := json.Marshal(vfsPayload)
	if err != nil {
		return "", fmt.Errorf("marshal vfs: %w", err)
	}
	cfgJSON, err := json.Marshal(nextCfg)
	if err != nil {
		return "", fmt.Errorf("marshal nextConfig: %w", err)
	}

	var b strings.Builder
	b.WriteString("// GENERATED BY nextcompile (nextserver engine) — DO NOT EDIT.\n")
	b.WriteString("// In-memory Virtual Filesystem for NextNodeServer manifests.\n\n")
	fmt.Fprintf(&b, "export const distDir = %q;\n", distDir)
	fmt.Fprintf(&b, "export const nextConfig = %s;\n", cfgJSON)
	fmt.Fprintf(&b, "export const vfs = %s;\n", vfsJSON)

	outPath := filepath.Join(dir, "vfs.mjs")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o600); err != nil {
		return "", fmt.Errorf("write vfs.mjs: %w", err)
	}
	return outPath, nil
}

func collectVFSFiles(standaloneDir, distDir string) map[string]string {
	files := map[string]string{}
	addFile := func(relPath, absPath string) {
		info, err := os.Stat(absPath)
		if err != nil || info.IsDir() || info.Size() > maxVFSFileBytes {
			return
		}
		data, err := os.ReadFile(absPath) // #nosec G304 — reading compiler input build artifacts
		if err != nil {
			return
		}
		files[filepath.ToSlash(relPath)] = string(data)
	}

	addFile("package.json", filepath.Join(standaloneDir, "package.json"))

	nextRoot := filepath.Join(standaloneDir, distDir)
	if _, err := os.Stat(nextRoot); err != nil {
		return files
	}
	_ = filepath.WalkDir(nextRoot, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			// Static client assets & standalone mirror live in R2, never in VFS.
			switch d.Name() {
			case "static", "cache", "standalone", "trace":
				return filepath.SkipDir
			}
			return nil
		}
		if !shouldInlineInVFS(d.Name()) {
			return nil
		}
		if rel, err := filepath.Rel(standaloneDir, p); err == nil {
			addFile(rel, p)
		}
		return nil
	})
	return files
}

func shouldInlineInVFS(name string) bool {
	if name == "BUILD_ID" || name == "package.json" {
		return true
	}
	if strings.HasSuffix(name, ".nft.json") || strings.HasSuffix(name, ".map") {
		return false
	}
	return strings.HasSuffix(name, ".json") || strings.HasSuffix(name, ".meta")
}

func buildVFSDirectoryIndex(files map[string]string) map[string][]string {
	dirSets := map[string]map[string]struct{}{
		"": {},
	}
	for filePath := range files {
		parts := strings.Split(filePath, "/")
		for i := range parts {
			parent := strings.Join(parts[:i], "/")
			child := parts[i]
			if _, ok := dirSets[parent]; !ok {
				dirSets[parent] = map[string]struct{}{}
			}
			dirSets[parent][child] = struct{}{}
			if i < len(parts)-1 {
				subDir := strings.Join(parts[:i+1], "/")
				if _, ok := dirSets[subDir]; !ok {
					dirSets[subDir] = map[string]struct{}{}
				}
			}
		}
	}

	out := make(map[string][]string, len(dirSets))
	for dirPath, children := range dirSets {
		list := make([]string, 0, len(children))
		for c := range children {
			list = append(list, c)
		}
		sort.Strings(list)
		out[dirPath] = list
	}
	return out
}

func extractNextConfigFromVFS(files map[string]string, distDir string) map[string]any {
	key := filepath.ToSlash(filepath.Join(distDir, "required-server-files.json"))
	raw, ok := files[key]
	if !ok {
		return map[string]any{}
	}
	var doc struct {
		Config map[string]any `json:"config"`
	}
	if err := json.Unmarshal([]byte(raw), &doc); err != nil || doc.Config == nil {
		return map[string]any{}
	}
	return doc.Config
}

const chunkLoaderRuntimeJS = `function normalizeModuleKey(raw) {
  if (typeof raw !== "string" || !raw) return "";
  const cleaned = raw.replace(/\\/g, "/");
  const parts = [];
  for (const seg of cleaned.split("/")) {
    if (!seg || seg === ".") continue;
    if (seg === "..") {
      if (parts.length > 0) parts.pop();
    } else {
      parts.push(seg);
    }
  }
  const joined = parts.join("/");
  if (Object.prototype.hasOwnProperty.call(serverModules, joined)) return joined;
  const idx = joined.indexOf(SERVER_PREFIX);
  if (idx >= 0) {
    const sub = joined.slice(idx);
    if (Object.prototype.hasOwnProperty.call(serverModules, sub)) return sub;
  }
  const stripped = joined.replace(/^\/+/, "");
  const distPrefixed = DIST_PREFIX + stripped;
  if (Object.prototype.hasOwnProperty.call(serverModules, distPrefixed)) return distPrefixed;
  const prefixed = SERVER_PREFIX + stripped;
  if (Object.prototype.hasOwnProperty.call(serverModules, prefixed)) return prefixed;
  if (!joined.endsWith(".js")) {
    for (const ext of [".js", ".cjs", ".mjs"]) {
      for (const base of [joined, distPrefixed, prefixed]) {
        const cand = base + ext;
        if (Object.prototype.hasOwnProperty.call(serverModules, cand)) return cand;
      }
    }
  }
  return "";
}

export function loadServerModule(rawPath) {
  const key = normalizeModuleKey(rawPath);
  if (!key) return undefined;
  return serverModules[key]();
}
`

func collectServerChunkPaths(standaloneDir, distDir string) ([]string, error) {
	serverDir := filepath.Join(standaloneDir, distDir, "server")
	if _, err := os.Stat(serverDir); err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("stat server dir: %w", err)
	}
	var relPaths []string
	err := filepath.WalkDir(serverDir, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			return nil
		}
		ext := strings.ToLower(filepath.Ext(d.Name()))
		if ext != ".js" && ext != ".cjs" && ext != ".mjs" {
			return nil
		}
		rel, relErr := filepath.Rel(standaloneDir, p)
		if relErr != nil {
			return relErr
		}
		relPaths = append(relPaths, filepath.ToSlash(rel))
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("walk server chunks: %w", err)
	}
	sort.Strings(relPaths)
	return relPaths, nil
}

// EmitChunkRegistry walks <standaloneDir>/<distDir>/server/ and emits
// <outDir>/_nextdeploy/chunks.mjs containing static `() => require(...)` thunks
// for every compiled server page, route, middleware, and Turbopack/Webpack chunk.
//
// Because every chunk is referenced by a static string literal, esbuild bundles
// all of them into worker.mjs, and runtime dynamic `require(chunkPath)` calls
// resolve synchronously from memory with zero filesystem access.
func EmitChunkRegistry(standaloneDir, distDir, outDir string) (string, error) {
	if distDir == "" {
		distDir = ".next"
	}
	dir := filepath.Join(outDir, "_nextdeploy")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return "", fmt.Errorf("mkdir _nextdeploy: %w", err)
	}

	relPaths, err := collectServerChunkPaths(standaloneDir, distDir)
	if err != nil {
		return "", err
	}

	prefix := importPrefixFor(dir, standaloneDir)
	distPrefix := filepath.ToSlash(distDir) + "/"
	serverPrefix := filepath.ToSlash(filepath.Join(distDir, "server")) + "/"

	var b strings.Builder
	b.WriteString("// GENERATED BY nextcompile (nextserver engine) — DO NOT EDIT.\n")
	b.WriteString("// Static server chunk registry enabling synchronous dynamic require() for Turbopack & Webpack.\n\n")
	b.WriteString("export const serverModules = Object.freeze({\n")
	for _, rel := range relPaths {
		fmt.Fprintf(&b, "  %s: () => require(%s),\n", jsStringLiteral(rel), jsStringLiteral(importPath(rel, prefix)))
	}
	b.WriteString("});\n\n")
	fmt.Fprintf(&b, "const DIST_PREFIX = %q;\n", distPrefix)
	fmt.Fprintf(&b, "const SERVER_PREFIX = %q;\n\n", serverPrefix)
	b.WriteString(chunkLoaderRuntimeJS)

	outPath := filepath.Join(dir, "chunks.mjs")
	if err := os.WriteFile(outPath, []byte(b.String()), 0o600); err != nil {
		return "", fmt.Errorf("write chunks.mjs: %w", err)
	}
	return outPath, nil
}

const nextServerEntryTemplate = `// GENERATED BY nextcompile (nextserver engine) — DO NOT EDIT.
// Cloudflare Worker entrypoint backed by Next.js's own NextNodeServer,
// an in-memory Virtual Filesystem, and a static Turbopack/Webpack chunk registry.

import {
  installNextServerGlobals,
  dispatchNextServer,
} from "./runtime/nextserver/nextserver_driver.mjs";
import { runGuard } from "./runtime/guard.mjs";
import { vfs, nextConfig, distDir } from "./vfs.mjs";
import { loadServerModule } from "./chunks.mjs";
import manifest from "./manifest.json" with { type: "json" };
import protection from "./protection.json" with { type: "json" };

installNextServerGlobals({
  vfs,
  loadServerModule,
  assetVersion: manifest?.assetVersion || "",
});

async function createNextServer() {
  const mod = await import("next/dist/server/next-server.js");
  const NextNodeServer = mod.default?.default || mod.default || mod;
  return new NextNodeServer({
    dir: "/",
    dev: false,
    conf: {
      ...nextConfig,
      distDir: distDir || ".next",
      cacheHandler: "__nextdeploy_cf_cache_handler__",
      cacheMaxMemorySize: 0,
    },
    customServer: false,
    minimalMode: false,
  });
}

const driverOpts = {
  manifest,
  guard: runGuard,
  protection,
  createServer: createNextServer,
};

export default {
  async fetch(request, env, ctx) {
    return dispatchNextServer(request, env, ctx, driverOpts);
  },
  async scheduled(event, env, ctx) {
    const cronUrl = new URL("/api/cron", "http://localhost");
    const req = new Request(cronUrl, {
      method: "POST",
      headers: {
        "x-cron-trigger": event.cron || "",
        "content-type": "application/json",
      },
      body: JSON.stringify({
        cron: event.cron,
        scheduledTime: event.scheduledTime,
      }),
    });
    ctx.waitUntil(
      dispatchNextServer(req, env, ctx, driverOpts)
        .then((res) => {
          if (!res.ok && res.status !== 404) {
            console.warn("[scheduled warning] cron handler returned status", res.status);
          }
        })
        .catch((err) => console.error("[scheduled error]", err)),
    );
  },
  async queue(batch, env, ctx) {
    const queueUrl = new URL("/api/queue/" + encodeURIComponent(batch.queue || ""), "http://localhost");
    const messages = (batch.messages || []).map((m) => ({
      id: m.id,
      timestamp: m.timestamp,
      body: m.body,
    }));
    const req = new Request(queueUrl, {
      method: "POST",
      headers: {
        "x-queue-name": batch.queue || "",
        "content-type": "application/json",
      },
      body: JSON.stringify({
        queue: batch.queue,
        messages,
      }),
    });
    ctx.waitUntil(
      dispatchNextServer(req, env, ctx, driverOpts)
        .then((res) => {
          if (!res.ok && res.status !== 404) {
            console.warn("[queue warning] queue handler returned status", res.status);
          }
        })
        .catch((err) => console.error("[queue error]", err)),
    );
  },
};
`

// EmitNextServerEntry writes the NextNodeServer-backed Worker entrypoint to
// <outDir>/_nextdeploy/worker_entry.mjs.
func EmitNextServerEntry(outDir string) (string, error) {
	dir := filepath.Join(outDir, "_nextdeploy")
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return "", fmt.Errorf("mkdir _nextdeploy: %w", err)
	}
	path := filepath.Join(dir, "worker_entry.mjs")
	if err := os.WriteFile(path, []byte(nextServerEntryTemplate), 0o600); err != nil {
		return "", fmt.Errorf("write nextserver worker_entry.mjs: %w", err)
	}
	return path, nil
}
